export const getFontFamilyStack = (fontName: string) => {
  if (!fontName) return '"Outfit", sans-serif';
  if (fontName === "SF Pro") {
    return `-apple-system, BlinkMacSystemFont, "SF Pro Display", "SF Pro Text", "Segoe UI", Roboto, Helvetica, Arial, sans-serif`;
  }
  if (fontName === "New York") {
    return `"New York", Georgia, "Times New Roman", serif`;
  }
  if (fontName === "SF Mono") {
    return `"SF Mono", Consolas, "Courier New", monospace`;
  }
  if (fontName === "Segoe UI") {
    return `"Segoe UI", -apple-system, Roboto, Helvetica, Arial, sans-serif`;
  }
  if (fontName === "Helvetica Neue") {
    return `"Helvetica Neue", Helvetica, Arial, sans-serif`;
  }
  if (fontName === "Trebuchet MS") {
    return `"Trebuchet MS", "Lucida Sans Unicode", "Lucida Grande", sans-serif`;
  }
  if (fontName === "Verdana") {
    return `Verdana, Geneva, sans-serif`;
  }
  if (fontName === "Times New Roman") {
    return `"Times New Roman", Times, serif`;
  }
  if (fontName === "Courier New") {
    return `"Courier New", Courier, monospace`;
  }
  if (fontName === "Arial") {
    return `Arial, Helvetica, sans-serif`;
  }
  if (fontName === "Palatino") {
    return `"Palatino Linotype", "Book Antiqua", Palatino, serif`;
  }
  if (fontName === "Impact") {
    return `Impact, Haettenschweiler, "Arial Narrow Bold", sans-serif`;
  }
  if (fontName === "Gill Sans") {
    return `"Gill Sans", "Gill Sans MT", Calibri, sans-serif`;
  }
  return `"${fontName}", sans-serif`;
};
